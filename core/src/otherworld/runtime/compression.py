"""Memory compression. See About/spec.md §5.4.

Runs whenever an agent's episodic count exceeds `memory.episodic_cap`:
synthesises the `memory.compression_batch` lowest-importance episodics
(oldest first among ties) into a single belief and deletes them, so
long-running agents (About/plan.md T5.1's 10,000-tick run) don't grow
memory tables without bound.

Protected from compression: spec.md says "any memory referenced in a
ConflictRecord or a Highlight". Highlights aren't generated by anything in
this codebase yet (Output plane, a later milestone), so that half doesn't
apply yet. `ConflictRecord` itself doesn't carry memory ids (About/models/
relationship.py) — the closest faithful proxy available today is an edge's
`shared_memory_ids` for any edge that has ever logged a conflict, which is
what's protected here. Revisit if `ConflictRecord` grows a memory-ids field.

Only the most recent `_RECENT_PROTECTED_PER_EDGE` shared memories per
conflicted edge are protected, not the edge's whole (unbounded)
`shared_memory_ids` history — About/plan.md T5.1's pilot run found that
protecting everything meant any busy, ever-conflicted pair permanently
shielded its entire shared history, so compression could never actually
bring some agents back under `episodic_cap` at all (observed: several
agents past 3x the cap, still climbing). This still protects what a real
highlight/story generator would plausibly want to keep, without the
protected set itself growing without bound right alongside the problem
it exists to guard against.
"""

from __future__ import annotations

import random
import uuid
from datetime import datetime

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from otherworld.config import settings
from otherworld.llm.protocol import LLMProvider
from otherworld.models.memory import MemoryKind, MemoryRecord, MemoryRecordORM, memory_to_orm
from otherworld.models.relationship import RelationshipEdgeORM
from otherworld.runtime.determinism import seeded_uuid

_RECENT_PROTECTED_PER_EDGE = 20


async def _protected_memory_ids(session: AsyncSession, agent_id: uuid.UUID) -> set[uuid.UUID]:
    rows = (
        await session.execute(
            select(RelationshipEdgeORM).where(
                (RelationshipEdgeORM.agent_a_id == agent_id) | (RelationshipEdgeORM.agent_b_id == agent_id)
            )
        )
    ).scalars().all()
    protected: set[uuid.UUID] = set()
    for row in rows:
        if row.conflict_log:
            recent = row.shared_memory_ids[-_RECENT_PROTECTED_PER_EDGE:]
            protected.update(uuid.UUID(i) for i in recent)
    return protected


async def compress_if_over_cap(
    session: AsyncSession,
    provider: LLMProvider,
    rng: random.Random,
    agent_id: uuid.UUID,
    tick: int,
    created_at: datetime,
) -> MemoryRecord | None:
    """Returns the synthesised belief if compression ran, else `None` —
    either because the agent is under the cap, or every over-cap candidate
    happened to be protected.
    """
    count = (
        await session.execute(
            select(func.count()).select_from(MemoryRecordORM).where(
                MemoryRecordORM.agent_id == agent_id, MemoryRecordORM.kind == MemoryKind.EPISODIC.value
            )
        )
    ).scalar_one()
    if count <= settings.memory.episodic_cap:
        return None

    protected = await _protected_memory_ids(session, agent_id)
    # Fetching *all* over-cap episodics to sort them in Python was another
    # of T5.1's profiled bugs (About/runtime/retrieval.py carries the full
    # writeup) — a small margin over `compression_batch` covers the
    # (typically few) protected rows that get filtered out below, without
    # ever pulling the agent's whole episodic history into Python.
    # Ordered by importance first, tick only as a tiebreaker — About/spec.md
    # §5.4 says "lowest-importance", and the M4 real trial found the reverse
    # order (tick first) silently defeats that: an old-but-significant
    # memory (a first encounter, a bond-state change) sits at the very
    # front of the deletion queue purely for being old, while newer routine
    # chatter survives — even though it's the routine chatter spec.md means
    # to prune. Importance-first actually protects meaningful memories the
    # way the module's own "protected from compression" section intends,
    # without needing every one of them tied to a `ConflictRecord`.
    fetch_limit = settings.memory.compression_batch + max(len(protected), 50)
    candidates = (
        await session.execute(
            select(MemoryRecordORM)
            .where(MemoryRecordORM.agent_id == agent_id, MemoryRecordORM.kind == MemoryKind.EPISODIC.value)
            .order_by(MemoryRecordORM.importance.asc(), MemoryRecordORM.tick.asc())
            .limit(fetch_limit)
        )
    ).scalars().all()

    batch = [row for row in candidates if row.id not in protected][: settings.memory.compression_batch]
    if not batch:
        return None

    content = f"A compressed memory of {len(batch)} minor moments from around tick {batch[0].tick}."
    embedding = await provider.embed(content)
    belief = MemoryRecord(
        id=seeded_uuid(rng),
        agent_id=agent_id,
        kind=MemoryKind.BELIEF,
        content=content,
        embedding=embedding,
        importance=sum(r.importance for r in batch) / len(batch),
        tick=tick,
        subjects=[agent_id],
        derived_from=[row.id for row in batch],
        created_at=created_at,
    )
    session.add(memory_to_orm(belief))
    for row in batch:
        await session.delete(row)

    await session.flush()
    return belief
